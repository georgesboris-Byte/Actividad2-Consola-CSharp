double CalcularAreaTriangulo(double baseTriangulo, double altura)
{
    return (baseTriangulo * altura) / 2.0;
}

double CalcularAreaCuadrado(double lado)
{
    return lado * lado;
}

double CalcularAreaCirculo(double radio)
{
    return Math.PI * radio * radio;
}